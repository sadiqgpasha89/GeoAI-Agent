"""Perception tools: scene description, visual Q&A and object grounding (VLM in live mode, deterministic in demo)."""

from __future__ import annotations

from typing import Any

from pydantic import BaseModel, Field
from shapely.geometry import box

from geoai.geo.regions import fraction_inside
from geoai.schemas import Domain, Observation
from geoai.tools import crop, earthquake, flood, urban, wildfire
from geoai.tools.base import Finding, NoArgs, ToolContext, ToolError, ToolOutput, make_obs
from geoai.tools.common import plural, where
from geoai.tools.grounding import demo_ground, region_filter

DOMAIN_TOOLS = {
    Domain.flood: (flood.TOOL, flood.assess_flood),
    Domain.wildfire: (wildfire.TOOL, wildfire.assess_wildfire),
    Domain.earthquake: (earthquake.TOOL, earthquake.assess_earthquake),
    Domain.urban: (urban.TOOL, urban.assess_urban),
    Domain.agriculture: (crop.TOOL, crop.assess_crop_health),
}
ALL_ASSESS = {flood.TOOL: flood.assess_flood, wildfire.TOOL: wildfire.assess_wildfire, earthquake.TOOL: earthquake.assess_earthquake,
              urban.TOOL: urban.assess_urban, crop.TOOL: crop.assess_crop_health}
MAX_VLM_CONF = 0.85  # model-proposed boxes are never treated as ground truth


def cached_assessment(ctx: ToolContext, tool: str) -> ToolOutput:
    return ctx.cached(f"tool:{tool}", lambda: ALL_ASSESS[tool](ctx, NoArgs()))


class DescribeArgs(NoArgs):
    pass


class QAArgs(BaseModel):
    question: str = Field(min_length=2, max_length=1000)


class GroundArgs(BaseModel):
    query: str = Field(min_length=2, max_length=300, description="Object to localise, e.g. 'flooded buildings' or 'Boeing 747 at the bottom left'")


def _context(ctx: ToolContext) -> dict[str, Any]:
    r = ctx.latest.raster
    return {"domain": ctx.domain.value, "gsd_m": r.gsd_m, "crs": r.georef.crs if r.georef else None,
            "captured_at": r.captured_at.isoformat() if r.captured_at else None, "width": r.width, "height": r.height}


def _vlm_obs(ctx: ToolContext, tool: str, boxes, prefix: str) -> list[Observation]:
    out = []
    h, w = ctx.shape
    for b in boxes:
        x0, y0, x1, y1 = b.bbox_px
        if x1 <= x0 or y1 <= y0:
            continue
        out.append(make_obs(ctx, tool, prefix, b.label, box(x0, y0, x1, y1), min(b.confidence, MAX_VLM_CONF),
                            attributes={"source": "vlm", "verification": "unverified"}))
    return out


def describe_scene(ctx: ToolContext, _args: NoArgs) -> ToolOutput:
    out = ToolOutput()
    r = ctx.latest.raster
    h, w = ctx.shape
    if ctx.gateway.mode == "live":
        d = ctx.gateway.describe(r.to_png_bytes(), w, h, _context(ctx))
        out.text = d.description
        out.observations += _vlm_obs(ctx, "describe_scene", d.objects, "obj")
        out.findings.append(Finding(text=d.description, topics=["describe", "summary"], kind="observed"))
        out.limitations.append("Scene description was generated by a vision-language model and has not been verified against measurements.")
        out.confidence = 0.7
        return out
    lc = urban.landcover(r)
    total = float(h * w)
    shares = sorted(((k, float(v.sum() / total)) for k, v in lc.items()), key=lambda kv: -kv[1])
    scale = ""
    if ctx.georef and r.gsd_m:
        scale = f" covering about {w * r.gsd_m / 1000:.2f} × {h * r.gsd_m / 1000:.2f} km at {r.gsd_m:.2g} m/pixel"
    layers = ""
    if ctx.layers:
        parts = [plural(len(v), k.rstrip("s").replace("_", " ")) for k, v in ctx.layers.layers.items() if v]
        layers = f" Reference layers list {', '.join(parts)}." if parts else ""
    top = ", ".join(f"{k.replace('built', 'built-up/impervious')} {v * 100:.0f}%" for k, v in shares if v >= 0.03)
    text = f"The image{scale} ({w}×{h} px, {'multispectral' if r.has_nir else 'RGB'}) is dominated by: {top}.{layers}"
    out.text = text
    out.findings.append(Finding(text=text, topics=["describe"], kind="observed"))
    out.limitations.append("Demo engine: descriptions come from classical measurements and reference layers, not a vision-language model.")
    out.confidence = 0.75
    return out


def visual_qa(ctx: ToolContext, args: QAArgs) -> ToolOutput:
    out = ToolOutput()
    h, w = ctx.shape
    images = [("latest", ctx.latest.raster.to_png_bytes())]
    if ctx.before is not None:
        images.insert(0, ("earlier", ctx.before.raster.to_png_bytes()))
    a = ctx.gateway.answer(images, args.question, w, h, _context(ctx))
    out.text = a.answer
    out.confidence = min(a.confidence, MAX_VLM_CONF)
    out.observations += _vlm_obs(ctx, "visual_qa", a.boxes, "qa")
    out.findings.append(Finding(text=a.answer, topics=["qa", "summary"], kind="observed"))
    out.limitations.append("Answer generated by a vision-language model; verify against measurements where available.")
    if out.confidence < ctx.settings.review_confidence_threshold:
        out.review_reasons.append(f"The vision model reported low confidence ({out.confidence:.0%}).")
    return out


def ground_object(ctx: ToolContext, args: GroundArgs) -> ToolOutput:
    out = ToolOutput()
    h, w = ctx.shape
    flt = region_filter(args.query, w, h)
    if ctx.gateway.mode == "live":
        boxes = ctx.gateway.locate(ctx.latest.raster.to_png_bytes(), args.query, w, h)
        obs = _vlm_obs(ctx, "ground_object", boxes, "obj")
        mask = None
        q = args.query.lower()
        if any(k in q for k in ("water", "flood", "river", "lake", "inundat")):
            from geoai.tools.common import water_masks

            mask = water_masks(ctx)[0]
        for o in obs:  # deterministic cross-check where a classical signal exists
            if mask is not None:
                frac = fraction_inside(mask, box(*o.bbox_px))
                o.attributes.update(verification="water-mask", water_overlap_pct=round(100 * frac, 1))
                o.confidence = round(min(o.confidence, 0.4 + 0.5 * frac + 0.1), 3)
        label = args.query
    else:
        def run(tool: str) -> list[Observation]:
            return cached_assessment(ctx, tool).observations

        obs, label = demo_ground(ctx, args.query, run)
        if label is None:
            out.findings.append(Finding(
                text=f"No object matching “{args.query}” could be located: the demo engine supports water/flood, buildings (flooded, damaged, collapsed), roads, burn scars, fire, smoke, "
                     "debris, fields (stressed), parks and construction. Configure a vision-language model for open-vocabulary grounding.",
                topics=["locate"], kind="not_determinable"))
            out.limitations.append("Open-vocabulary grounding requires a VLM provider (set ANTHROPIC_API_KEY).")
            return out
    if flt:
        obs = [o for o in obs if o.bbox_px and flt(o.bbox_px)]
    out.observations = obs
    if obs:
        pos = ", ".join(sorted({where(o.bbox_px, w, h) for o in obs}))
        out.findings.append(Finding(text=f"Located {plural(len(obs), 'region')} for “{args.query}” ({pos}). Boxes are in image pixel coordinates.", topics=["locate"], kind="observed"))
        out.confidence = sum(o.confidence for o in obs) / len(obs)
    else:
        out.findings.append(Finding(text=f"No “{args.query}” was found in the image" + (" within the requested region." if flt else "."), topics=["locate"], kind="not_determinable"))
        out.confidence = 0.6
    if label and ctx.gateway.mode == "demo" and obs:
        out.limitations.append("Demo engine: regions come from classical measurements and reference layers.")
    return out


SPECS = [
    dict(name="describe_scene", description="Describe the scene in detail (VLM in live mode; measurements in demo mode).", args_model=DescribeArgs, fn=describe_scene),
    dict(name="visual_qa", description="Answer an open-ended question about the imagery with a vision-language model.", args_model=QAArgs, fn=visual_qa),
    dict(name="ground_object", description="Locate a requested object and return bounding boxes (or 'not found').", args_model=GroundArgs, fn=ground_object),
]

__all__ = ["DOMAIN_TOOLS", "SPECS", "ToolError", "cached_assessment"]
